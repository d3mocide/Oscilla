#!/usr/bin/env python3
"""Generate packed 1-bit flash bitmap fonts for Oscilla Observatory v2 UI.

Input TTFs (SIL Open Font License 1.1):
  - ChakraPetch-Bold.ttf (Head 12px, Title 16px, Hero 20px)
  - IBMPlexMono-Medium.ttf (Mono 11px)

Usage:
  python3 tools/gen_observatory_fonts.py --fonts-dir <dir-with-ttfs>
"""
import argparse
from pathlib import Path
from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[1]
FIRST_CHAR = 0x20
LAST_CHAR = 0x7E

SPECS = [
    ("Head",  "ChakraPetch-Bold.ttf",   12, "L", 115, 1),
    ("Title", "ChakraPetch-Bold.ttf",   16, "L", 112, 0),
    ("Hero",  "ChakraPetch-Bold.ttf",   20, "L", 112, 0),
    ("Mono",  "IBMPlexMono-Medium.ttf", 11, "1",   0, 0),
]


def rasterize_font(ttf_path: Path, size: int, mode: str, thresh: int, tracking: int):
    font = ImageFont.truetype(str(ttf_path), size)
    # Anchor vertical origin to the top of capital 'H' so y=top aligns caps cleanly.
    h_box = font.getbbox("H")
    cap_top = h_box[1]
    cap_height = h_box[3] - h_box[1]
    ascent, descent = font.getmetrics()
    line_height = max(cap_height + 2, ascent + descent)

    bitmap = bytearray()
    glyphs = []
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        adv = max(1, int(round(font.getlength(ch))) + tracking)
        if ch == " ":
            glyphs.append((0, 0, 0, adv, 0, 0))
            continue
        mask = font.getmask(ch, mode=mode)
        bbox = font.getbbox(ch)
        if not bbox or mask.size[0] == 0 or mask.size[1] == 0:
            glyphs.append((0, 0, 0, adv, 0, 0))
            continue
        bx0, by0, _, _ = bbox
        mw, mh = mask.size
        # Extract binary grid and trim empty margins so flash stays tight.
        rows = []
        for r in range(mh):
            row_bits = []
            for c in range(mw):
                v = mask.getpixel((c, r))
                row_bits.append(1 if ((mode == "1" and v) or (mode == "L" and v >= thresh)) else 0)
            rows.append(row_bits)

        min_r, max_r = mh, -1
        min_c, max_c = mw, -1
        for r in range(mh):
            for c in range(mw):
                if rows[r][c]:
                    min_r = min(min_r, r)
                    max_r = max(max_r, r)
                    min_c = min(min_c, c)
                    max_c = max(max_c, c)
        if max_r < min_r:
            glyphs.append((0, 0, 0, adv, 0, 0))
            continue

        gw = max_c - min_c + 1
        gh = max_r - min_r + 1
        x_off = bx0 + min_c
        y_off = (by0 + min_r) - cap_top
        offset = len(bitmap)
        stride = (gw + 7) // 8
        for r in range(min_r, max_r + 1):
            for byte_i in range(stride):
                b = 0
                for bit in range(8):
                    c = min_c + byte_i * 8 + bit
                    if c <= max_c and rows[r][c]:
                        b |= 0x80 >> bit
                bitmap.append(b)
        glyphs.append((offset, gw, gh, adv, x_off, y_off))

    return {
        "bitmap": bytes(bitmap),
        "glyphs": glyphs,
        "line_height": line_height,
        "cap_height": cap_height,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts-dir", type=Path, required=True)
    args = parser.parse_args()

    out_h = ROOT / "firmware-cardputer/src/ui/observatory_fonts.h"
    out_cpp = ROOT / "firmware-cardputer/src/ui/observatory_fonts.cpp"

    header = """/*
 * observatory_fonts.h — 1-bit flash bitmap fonts for Observatory v2 UI.
 *
 * Generated by tools/gen_observatory_fonts.py from Chakra Petch Bold and
 * IBM Plex Mono Medium (SIL Open Font License 1.1; see NOTICE).
 * Authority: docs/brand/README.md.
 *
 * SPDX-License-Identifier: MIT
 */

#pragma once

#include <cstdint>

namespace ui {
namespace observatory {

enum class FontId : uint8_t { Head = 0, Title = 1, Hero = 2, Mono = 3 };

struct Glyph {
    uint16_t offset;
    uint8_t width;
    uint8_t height;
    uint8_t x_advance;
    int8_t x_offset;
    int8_t y_offset;
};

struct Font {
    const uint8_t *bitmap;
    const Glyph *glyphs;
    uint8_t first_char;
    uint8_t last_char;
    uint8_t cap_height;
    uint8_t line_height;
};

const Font &font(FontId id);

}  // namespace observatory
}  // namespace ui
"""
    out_h.write_text(header)

    parts = [
        "/* Generated by tools/gen_observatory_fonts.py — do not hand-edit. */",
        '#include "ui/observatory_fonts.h"',
        "",
        "namespace ui {",
        "namespace observatory {",
        "namespace {",
        "",
    ]

    total_bytes = 0
    for name, fname, size, mode, thresh, tracking in SPECS:
        data = rasterize_font(args.fonts_dir / fname, size, mode, thresh, tracking)
        bm = data["bitmap"]
        total_bytes += len(bm) + len(data["glyphs"]) * 7
        parts.append(f"/* {fname} @ {size}px ({len(bm)} B bitmap) */")
        parts.append(f"const uint8_t k{name}Bitmap[] = {{")
        for i in range(0, len(bm), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in bm[i:i + 16])
            parts.append(f"    {chunk},")
        parts.append("};")
        parts.append(f"const Glyph k{name}Glyphs[] = {{")
        for g in data["glyphs"]:
            parts.append(f"    {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}},")
        parts.append("};")
        parts.append(
            f"const Font k{name}Font = {{k{name}Bitmap, k{name}Glyphs, "
            f"0x{FIRST_CHAR:02X}, 0x{LAST_CHAR:02X}, {data['cap_height']}, {data['line_height']}}};"
        )
        parts.append("")

    parts.extend([
        "}  // namespace",
        "",
        "const Font &font(FontId id) {",
        "    switch (id) {",
        "        case FontId::Head:  return kHeadFont;",
        "        case FontId::Title: return kTitleFont;",
        "        case FontId::Hero:  return kHeroFont;",
        "        case FontId::Mono:  return kMonoFont;",
        "    }",
        "    return kMonoFont;",
        "}",
        "",
        "}  // namespace observatory",
        "}  // namespace ui",
        "",
    ])
    out_cpp.write_text("\n".join(parts))
    print(f"Generated {out_h.name} + {out_cpp.name} ({total_bytes} bytes total in flash)")


if __name__ == "__main__":
    main()
